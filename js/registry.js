// The station that owns a review problem (the first station in Story Map order that lists it,
// skipping the index and the Rehearsal Room). Used by the router for #problem-<id> deep links.
export function stationForProblem(problemId) {
  return STATIONS.find((s) => !META_STATIONS.includes(s.id) && s.problems.includes(problemId)) || null;
}

// The station that teaches a topic (first in Story Map order, skipping the index and the Rehearsal Room). Used for #topic-<id> deep links.
export function stationForTopic(topicId) {
  return STATIONS.find((s) => !META_STATIONS.includes(s.id) && s.topics.includes(topicId)) || null;
}

export function stationById(id) {
  return STATIONS.find((s) => s.id === id) || null;
}
