ok('hue',D.hueOf(C(1))===0&&near(D.hueOf(C(0,1)),0.25)&&near(D.hueOf(C(-1)),0.5)&&near(D.hueOf(C(0,-1)),0.75),[D.hueOf(C(1)),D.hueOf(C(0,1)),D.hueOf(C(-1)),D.hueOf(C(0,-1))]);
